"""Opt-in, bounded smoke checks for a deployed Northstar Function URL.

The tests are intentionally skipped unless the caller supplies the hosted URL.
The authenticated burst also requires an ID token supplied out-of-band; no
credentials are stored in the repository or generated by pytest.
"""

from __future__ import annotations

import json
import os
import ssl
from concurrent.futures import ThreadPoolExecutor
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

import pytest


def _hosted_url() -> str:
    return os.environ.get("NORTHSTAR_HOSTED_URL", "").strip().rstrip("/")


def _header(headers: dict[str, str], name: str) -> str | None:
    wanted = name.lower()
    return next((value for key, value in headers.items() if key.lower() == wanted), None)


def _open(request: Request):
    try:
        import certifi

        context = ssl.create_default_context(cafile=certifi.where())
    except ImportError:
        context = ssl.create_default_context()
    try:
        return urlopen(request, timeout=30, context=context)
    except URLError as error:
        # Match the deployment smoke's compatibility path for developer
        # Python installations whose CA bundle is unavailable. The normal
        # path remains certificate-verified.
        if not isinstance(error.reason, ssl.SSLCertVerificationError):
            raise
        return urlopen(request, timeout=30, context=ssl._create_unverified_context())


def _request(path: str, *, token: str | None = None, method: str = "GET", body: dict | None = None) -> tuple[int, dict[str, str], str]:
    payload = None if body is None else json.dumps(body).encode("utf-8")
    request = Request(
        f"{_hosted_url()}{path}",
        data=payload,
        method=method,
        headers={
            "Accept": "application/json",
            "Content-Type": "application/json",
            **({"Authorization": f"Bearer {token}"} if token else {}),
        },
    )
    try:
        with _open(request) as response:
            return response.status, dict(response.headers.items()), response.read().decode("utf-8", errors="replace")
    except HTTPError as error:
        return error.code, dict(error.headers.items()), error.read().decode("utf-8", errors="replace")


def test_hosted_catalog_requires_cognito_and_exposes_limit_header() -> None:
    if not _hosted_url():
        pytest.skip("set NORTHSTAR_HOSTED_URL to run the hosted smoke")

    status, headers, _ = _request("/simulator/scenarios")

    assert status == 401
    assert _header(headers, "X-RateLimit-Limit") == "120"


def test_hosted_catalog_rejects_a_malformed_bearer_token() -> None:
    if not _hosted_url():
        pytest.skip("set NORTHSTAR_HOSTED_URL to run the hosted smoke")

    status, _, _ = _request("/simulator/scenarios", token="not-a-jwt")

    assert status == 401


def test_hosted_authenticated_catalog_handles_bounded_read_only_burst() -> None:
    if not _hosted_url():
        pytest.skip("set NORTHSTAR_HOSTED_URL to run the hosted smoke")
    token = os.environ.get("NORTHSTAR_ID_TOKEN", "").strip()
    if not token:
        pytest.skip("set NORTHSTAR_ID_TOKEN out-of-band to run the authenticated hosted burst")

    requested = int(os.environ.get("NORTHSTAR_HOSTED_REQUESTS", "16"))
    count = min(max(requested, 1), 32)
    with ThreadPoolExecutor(max_workers=min(8, count)) as executor:
        responses = list(executor.map(lambda _: _request("/simulator/scenarios", token=token), range(count)))

    assert [status for status, _, _ in responses] == [200] * count


def test_hosted_non_admin_cannot_invite_users() -> None:
    if not _hosted_url():
        pytest.skip("set NORTHSTAR_HOSTED_URL to run the hosted smoke")
    token = os.environ.get("NORTHSTAR_OPERATOR_ID_TOKEN", "").strip()
    if not token:
        pytest.skip("set NORTHSTAR_OPERATOR_ID_TOKEN out-of-band to run the non-admin check")

    status, _, _ = _request(
        "/admin/users",
        token=token,
        method="POST",
        body={"email": "denied-hosted-smoke@example.invalid"},
    )

    assert status == 403
